/* pad.h - button bits shared by the BLE pad, the serial keys and the screens. */
#pragma once
#define PAD_UP      0x001
#define PAD_DOWN    0x002
#define PAD_LEFT    0x004
#define PAD_RIGHT   0x008
#define PAD_A       0x010
#define PAD_B       0x020
#define PAD_START   0x040
#define PAD_SELECT  0x080
#define PAD_MENU    0x100   /* opens the in-game menu (a pad button no SNES game uses) */
#define PAD_X       0x200
#define PAD_Y       0x400
#define PAD_L       0x800
#define PAD_R       0x1000
